const TMP = require('os').tmpdir();
const { ok, near, open, S, desk, state, summary } = require('./lib.cjs');
const fs = require('fs');
(async () => {
  const { browser, ctx, page, errors } = await open();
  await S(page, () => window.__rp.useProject.getState().updateRoom({ depth: 120 }));
  await S(page, () => window.__rp.useUi.getState().sendCanvasCmd('fit')); await page.waitForTimeout(250);
  const cv = await page.$eval('[data-testid="plan-canvas"]', e => { const r = e.getBoundingClientRect(); return { x: r.x, y: r.y }; });
  const at = async (xin, yin) => { const { vp } = await state(page); return { x: cv.x + vp.panX + xin * vp.zoom, y: cv.y + vp.panY + yin * vp.zoom }; };

  console.log('Library: click to add, drag onto the plan');
  await page.click('[data-testid="tpl-tpl-bookshelf"]').catch(async () => { await page.click('button:has-text("Storage")'); await page.click('[data-testid="tpl-tpl-bookshelf"]'); });
  await page.waitForTimeout(200);
  let st = await state(page);
  let layout = st.p.layouts[0];
  ok('clicking a library item adds it (2 pieces)', layout.furniture.length === 2, `${layout.furniture.length}`);
  const shelf = layout.furniture[1];
  ok('bookshelf has its library dimensions 36 x 12', shelf.width === 36 && shelf.depth === 12);
  ok('and is selected', st.sel && st.sel.id === shelf.id);
  const target = await at(80, 100);
  await page.click('button:has-text("Office")');
  await page.dragAndDrop('[data-testid="tpl-tpl-chair"]', '[data-testid="plan-canvas"]', { targetPosition: { x: target.x - cv.x, y: target.y - cv.y } });
  await page.waitForTimeout(250);
  st = await state(page);
  const chair = st.p.layouts[0].furniture.find(f => f.name === 'Office chair');
  ok('drag-drop from the library places a chair', !!chair);
  ok('dropped at the pointer (x≈80", y≈100")', chair && near(chair.x, 80, 2) && near(chair.y, 100, 2), chair && `${chair.x},${chair.y}`);

  console.log('Resize handles keep the opposite edge fixed');
  await S(page, (id) => { const s = window.__rp.useProject.getState(); s.updateFurniture(id, { x: 30, y: 90, rotation: 0 }); window.__rp.useUi.getState().select({ kind: 'furniture', id }); }, shelf.id);
  await page.waitForTimeout(250);
  const h = await page.$('g[data-handle="1,0"]'); const hb = await h.boundingBox(); const zoom = (await state(page)).vp.zoom;
  await page.mouse.move(hb.x + hb.width / 2, hb.y + hb.height / 2); await page.mouse.down();
  await page.mouse.move(hb.x + hb.width / 2 + 12 * zoom, hb.y + hb.height / 2, { steps: 8 }); await page.mouse.up(); await page.waitForTimeout(150);
  let s2 = (await state(page)).p.layouts[0].furniture.find(f => f.id === shelf.id);
  ok('east handle +12" widens to 48"', near(s2.width, 48, 0.2), `${s2.width}`);
  ok('west edge stayed fixed (x - w/2 = 12)', near(s2.x - s2.width / 2, 12, 0.2), `${s2.x - s2.width / 2}`);
  ok('depth unchanged', s2.depth === 12);

  console.log('Locking');
  await S(page, (id) => window.__rp.useProject.getState().updateFurniture(id, { locked: true }), shelf.id);
  await page.waitForTimeout(150);
  const g = await (await page.$(`g[data-id="${shelf.id}"]`)).boundingBox();
  const sx = (await state(page)).p.layouts[0].furniture.find(f => f.id === shelf.id).x;
  await page.mouse.move(g.x + g.width / 2, g.y + g.height / 2); await page.mouse.down(); await page.mouse.move(g.x + g.width / 2 + 80, g.y + g.height / 2 + 20, { steps: 6 }); await page.mouse.up();
  const sx2 = (await state(page)).p.layouts[0].furniture.find(f => f.id === shelf.id).x;
  ok('a locked piece cannot be dragged', sx === sx2);
  ok('no rotation handle on a locked piece', (await page.$$('g[data-hit="rotate"]')).length === 0);
  await S(page, (id) => window.__rp.useProject.getState().updateFurniture(id, { locked: false }), shelf.id);

  console.log('Hide / duplicate / delete / shortcuts');
  await S(page, (id) => window.__rp.useUi.getState().select({ kind: 'furniture', id }), shelf.id);
  await page.keyboard.press('Control+d'); await page.waitForTimeout(150);
  st = await state(page);
  ok('Ctrl+D duplicates', st.p.layouts[0].furniture.length === 4, `${st.p.layouts[0].furniture.length}`);
  const dup = st.p.layouts[0].furniture.find(f => f.name === 'Bookshelf copy');
  ok('copy is offset 12" and selected', dup && near(dup.x - 30 - 6, 12 - 6 + 0, 40) && st.sel.id === dup.id);
  await page.keyboard.press('Delete'); await page.waitForTimeout(150);
  ok('Delete removes the selection', (await state(page)).p.layouts[0].furniture.length === 3);
  await page.keyboard.press('Control+z'); await page.waitForTimeout(100);
  ok('and undo brings it back', (await state(page)).p.layouts[0].furniture.length === 4);
  await S(page, (id) => window.__rp.useUi.getState().select({ kind: 'furniture', id }), shelf.id);
  const x0 = (await state(page)).p.layouts[0].furniture.find(f => f.id === shelf.id).x;
  await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowRight'); await page.keyboard.press('Shift+ArrowDown'); await page.waitForTimeout(100);
  const sNow = (await state(page)).p.layouts[0].furniture.find(f => f.id === shelf.id);
  ok('arrow keys nudge 1" (Shift = 6")', near(sNow.x - x0, 2, 1e-6) && near(sNow.y - 90, 6, 1e-6), `${sNow.x - x0}, ${sNow.y - 90}`);
  await S(page, (id) => window.__rp.useProject.getState().updateFurniture(id, { hidden: true }), shelf.id);
  await page.waitForTimeout(150);
  ok('hidden pieces are not drawn', (await page.$$(`g[data-id="${shelf.id}"]`)).length === 0);
  await S(page, (id) => window.__rp.useProject.getState().updateFurniture(id, { hidden: false }), shelf.id);

  console.log('Layouts: save, switch, compare');
  await page.click('button:has-text("Save layout")'); await page.waitForTimeout(200);
  st = await state(page);
  ok('Save layout creates a second layout with the same furniture count', st.p.layouts.length === 2 && st.p.layouts[1].furniture.length === st.p.layouts[0].furniture.length);
  ok('furniture ids differ between layouts', st.p.layouts[1].furniture[0].id !== st.p.layouts[0].furniture[0].id);
  const bId = st.p.layouts[1].furniture.find(f => f.name.startsWith('L-shaped')).id;
  await S(page, (id) => window.__rp.useProject.getState().updateFurniture(id, { x: 66, y: 40 }), bId);
  await page.keyboard.press('1'); await page.waitForTimeout(150);
  ok('key "1" switches to Layout A', (await state(page)).p.activeLayoutId === st.p.layouts[0].id);
  const aDesk = await desk(page);
  ok('Layout A desk position independent of B', aDesk.x !== 66);
  await page.keyboard.press('2'); await page.waitForTimeout(150);
  ok('key "2" switches to Layout B', (await state(page)).p.activeLayoutId === st.p.layouts[1].id);
  await S(page, () => { const s = window.__rp.useProject.getState(); window.__rp.useUi.getState().setGhost(s.project.layouts[0].id); });
  await page.waitForTimeout(200);
  const ghosts = await page.$$eval('svg polygon', els => els.filter(e => e.getAttribute('fill') === 'none' && (e.getAttribute('stroke-dasharray') || '').length > 0 && e.getAttribute('stroke-opacity') === '0.55').length);
  ok('compare overlay draws the other layout faintly', ghosts >= 1, `${ghosts}`);
  await S(page, () => window.__rp.useUi.getState().setGhost(null));
  await S(page, () => { const s = window.__rp.useProject.getState(); s.updateRoom({ depth: 130 }); });
  await page.keyboard.press('1'); await page.waitForTimeout(100);
  ok('architecture is shared across layouts', (await state(page)).p.room.depth === 130);
  await page.keyboard.press('Control+z'); await page.waitForTimeout(100);

  console.log('Units');
  await S(page, () => window.__rp.useProject.getState().setSettings({ units: 'ftin' }));
  await page.waitForTimeout(200);
  ok("101\" shows as 8' 5\"", (await page.textContent('body')).includes(`8' 5"`));
  await S(page, () => window.__rp.useProject.getState().setSettings({ units: 'in' }));

  console.log('Persistence + import/export');
  await page.waitForTimeout(900);
  const snap = await state(page);
  const pngP = page.waitForEvent('download');
  await S(page, () => window.__rp.useUi.getState().setMode('furniture'));
  await page.click('button[aria-label="Project menu"]'); await page.click('text=Export PNG');
  const dl = await pngP; const path = await dl.path();
  const png = fs.readFileSync(path);
  ok('PNG export downloads a real PNG', png.slice(0, 8).toString('hex') === '89504e470d0a1a0a' && png.length > 20000, `${png.length} bytes ${dl.suggestedFilename()}`);
  const jsonP = page.waitForEvent('download');
  await page.click('button[aria-label="Project menu"]'); await page.click('text=Export project (JSON)');
  const jd = await jsonP; const jtext = fs.readFileSync(await jd.path(), 'utf8');
  const parsed = JSON.parse(jtext);
  ok('JSON export has the project', parsed.format === 'room-planner-project' && parsed.project.name === 'Office Layout');
  await page.reload(); await page.waitForFunction(() => window.__rp && document.querySelector('[data-testid="plan-svg"]')); await page.waitForTimeout(500);
  const re = await state(page);
  ok('autosave: project survives a reload (IndexedDB)', re.p.layouts.length === snap.p.layouts.length && re.p.room.depth === snap.p.room.depth && re.p.layouts[0].furniture.length === snap.p.layouts[0].furniture.length);
  await S(page, () => window.__rp.useProject.getState().resetToSeed());
  await page.waitForTimeout(150);
  fs.writeFileSync(TMP + '/rp-export.json', jtext);
  await page.click('button[aria-label="Project menu"]'); await page.setInputFiles('[data-testid="import-file"]', TMP + '/rp-export.json');
  await page.waitForTimeout(400);
  const imp = await state(page);
  ok('import restores the exported project', imp.p.layouts.length === snap.p.layouts.length && imp.p.room.depth === snap.p.room.depth);
  fs.writeFileSync(TMP + '/rp-bad.json', '{"hello": 1}');
  await page.click('button[aria-label="Project menu"]'); await page.setInputFiles('[data-testid="import-file"]', TMP + '/rp-bad.json'); await page.waitForTimeout(300);
  ok('importing a bad file is rejected without changing the project', (await state(page)).p.layouts.length === snap.p.layouts.length && /Import failed/.test(await page.textContent('body')));

  console.log('Presentation mode');
  await page.click('button[aria-label="Project menu"]'); await page.click('text=Presentation mode'); await page.waitForTimeout(200);
  ok('presentation hides the panels', (await page.$$('[aria-label="Properties"]')).length === 0 && (await page.$$('[aria-label="Library"]')).length === 0);
  await page.keyboard.press('Escape'); await page.waitForTimeout(150);
  ok('Esc exits presentation', (await page.$$('[aria-label="Properties"]')).length === 1);

  ok('no console errors', errors.length === 0, errors.join(' | '));
  await browser.close();
  process.exit(summary() ? 1 : 0);
})();
